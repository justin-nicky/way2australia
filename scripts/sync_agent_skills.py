#!/usr/bin/env python3
"""Mirror the canonical agent skills in ``agent-skills/`` to each tool's skill folder.

Usage:
    python3 scripts/sync_agent_skills.py          # regenerate mirrors
    python3 scripts/sync_agent_skills.py --check  # exit 1 if any mirror differs

Each mirrored skill folder contains a marker file so the script only prunes or
replaces folders it manages. Claude-only frontmatter is injected into the
``.claude/skills`` copies; other mirrors stay portable Agent Skills.
"""

from __future__ import annotations

import argparse
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "agent-skills"
TARGETS = {
    "claude": ROOT / ".claude" / "skills",
    "codex": ROOT / ".agents" / "skills",
    "kiro": ROOT / ".kiro" / "skills",
}
MARKER = ".synced-from-agent-skills"
MARKER_TEXT = (
    b"Generated by scripts/sync_agent_skills.py from agent-skills/. "
    b"Do not edit; edit agent-skills/ and run `make skills-sync`.\n"
)
HOST_FRONTMATTER = {
    "claude": {
        "spec-implementer": [
            "disable-model-invocation: true",
            "argument-hint: <NNN-spec-name>",
        ],
        "spec-reviewer": [
            "disable-model-invocation: true",
            "argument-hint: <NNN-spec-name>",
            "context: fork",
            "background: false",
        ],
    },
}

Tree = dict[str, bytes]


def discover_skills() -> list[str]:
    return sorted(path.parent.name for path in SOURCE.glob("*/SKILL.md"))


def read_tree(directory: Path) -> Tree:
    tree: Tree = {}
    for path in sorted(directory.rglob("*")):
        if path.is_symlink():
            tree[path.relative_to(directory).as_posix()] = b"<symlink>"
        elif path.is_file():
            tree[path.relative_to(directory).as_posix()] = path.read_bytes()
    return tree


def inject_frontmatter(skill_md: bytes, extra_lines: list[str]) -> bytes:
    text = skill_md.decode("utf-8")
    if not text.startswith("---\n"):
        raise ValueError("SKILL.md must start with YAML frontmatter")
    end = text.index("\n---\n", 4)
    extra = "".join(f"\n{line}" for line in extra_lines)
    return (text[:end] + extra + text[end:]).encode("utf-8")


def expected_tree(host: str, skill: str) -> Tree:
    tree = read_tree(SOURCE / skill)
    extra = HOST_FRONTMATTER.get(host, {}).get(skill)
    if extra:
        tree["SKILL.md"] = inject_frontmatter(tree["SKILL.md"], extra)
    tree[MARKER] = MARKER_TEXT
    return tree


def managed_skills(target: Path) -> set[str]:
    if not target.is_dir():
        return set()
    return {path.parent.name for path in target.glob(f"*/{MARKER}")}


def remove(path: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def find_problems(skills: list[str]) -> list[str]:
    problems: list[str] = []
    for host, target in TARGETS.items():
        for skill in skills:
            dst = target / skill
            label = dst.relative_to(ROOT).as_posix()
            if dst.is_symlink() or not dst.is_dir():
                problems.append(f"{label}: missing or not a directory")
            elif read_tree(dst) != expected_tree(host, skill):
                problems.append(f"{label}: differs from agent-skills/{skill}")
        for stale in sorted(managed_skills(target) - set(skills)):
            label = (target / stale).relative_to(ROOT).as_posix()
            problems.append(f"{label}: stale (no longer in agent-skills/)")
    return problems


def sync(skills: list[str], force: bool) -> None:
    unmanaged = [
        (target / skill).relative_to(ROOT).as_posix()
        for target in TARGETS.values()
        for skill in skills
        if (target / skill).exists() and not (target / skill / MARKER).exists()
    ]
    if unmanaged and not force:
        sys.exit(
            "Refusing to overwrite folders not created by this script "
            "(use --force):\n" + "\n".join(f" - {item}" for item in unmanaged)
        )

    for host, target in TARGETS.items():
        target.mkdir(parents=True, exist_ok=True)
        for skill in skills:
            staging = Path(tempfile.mkdtemp(prefix=f".{skill}-", dir=target))
            for relative, content in expected_tree(host, skill).items():
                file_path = staging / relative
                file_path.parent.mkdir(parents=True, exist_ok=True)
                file_path.write_bytes(content)
            remove(target / skill)
            staging.rename(target / skill)
        for stale in managed_skills(target) - set(skills):
            remove(target / stale)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Mirror agent-skills/ to tool folders."
    )
    parser.add_argument("--check", action="store_true", help="verify only")
    parser.add_argument(
        "--force", action="store_true", help="overwrite unmanaged skill folders"
    )
    args = parser.parse_args()

    skills = discover_skills()
    if not skills:
        print(f"No skills found under {SOURCE.relative_to(ROOT)}/")
        return 1
    if not args.check:
        sync(skills, force=args.force)

    problems = find_problems(skills)
    if problems:
        print("Agent skill mirrors are out of sync (run `make skills-sync`):")
        for problem in problems:
            print(f" - {problem}")
        return 1
    print(f"All skill mirrors match agent-skills/ ({len(skills)} skills).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
